"use strict";
// Offline benchmark of the ADSF prompt-injection scan against the committed LLMail-Inject samples.
// No network. Writes docs/LLMAIL_BENCHMARK.md; `--check` fails if the committed doc is out of date.
//   node scripts/bench-llmail.js [--check]
const fs = require("fs"), path = require("path");
const { scanText } = require("../src/scanners/injection.js");
const { loadRules } = require("../src/util.js");
const ROOT = path.join(__dirname, ".."), D = path.join(ROOT, "data", "llmail");
const read = (f) => fs.readFileSync(path.join(D, f), "utf8").trim().split("\n").map((l) => JSON.parse(l));
const RANK = { low: 1, medium: 2, high: 3 };

function run(rows, R) {
  const res = rows.map((r) => scanText(r.text, r.id, R));
  const at = (min) => res.filter((f) => f.some((x) => RANK[x.severity] >= min)).length;
  const byRule = {};
  res.forEach((f) => new Set(f.map((x) => x.rule)).forEach((k) => (byRule[k] = (byRule[k] || 0) + 1)));
  return { n: rows.length, any: at(1), medPlus: at(2), high: at(3), byRule };
}
function bench() {
  const full = loadRules("injection");
  const base = Object.assign({}, full, { llmail: [] });
  const sets = {
    heldout: read("attacks-phase2-heldout.jsonl"), p1: read("attacks-phase1-sample.jsonl"),
    benign: read("benign-fp-emails.jsonl"), hard: read("benign-hard-authored.jsonl")
  };
  const out = {};
  for (const [k, rows] of Object.entries(sets)) out[k] = { before: run(rows, base), after: run(rows, full) };
  return out;
}
const pct = (a, n) => (100 * a / n).toFixed(1) + "% (" + a + "/" + n + ")";
function render(b) {
  const row = (name, r, kind) => "| " + name + " | " + kind + " | " + pct(r.before.any, r.n || r.before.n) + " | " + pct(r.after.any, r.after.n) + " | " + pct(r.after.medPlus, r.after.n) + " |";
  const top = Object.entries(b.heldout.after.byRule).sort((x, y) => y[1] - x[1]).map(([k, v]) => "| `" + k + "` | " + v + " |");
  return [
    "# LLMail-Inject benchmark for the ADSF prompt-injection scan", "",
    "_Generated by `node scripts/bench-llmail.js` from the samples committed in `data/llmail/`. Offline; no network. Do not edit by hand._", "",
    "Data: [Microsoft LLMail-Inject](https://huggingface.co/datasets/microsoft/llmail-inject-challenge) (MIT License). Attack prompts were written by challenge participants trying to make an email assistant send an email it was not asked to send. See `THIRD_PARTY_NOTICES.md`.", "",
    "## Results", "",
    "\"Before\" = the ADSF rules that existed before this change. \"After\" = with the 8 LLMail-derived rules. \"Flagged\" means at least one finding of any severity; the last column ignores the low-severity `llmail_send_to_address` signal.", "",
    "| Set | Kind | Flagged before | Flagged after (any severity) | Flagged after (medium+) |", "|---|---|---|---|---|",
    row("Phase 2 held-out attacks", b.heldout, "detection rate"),
    row("Phase 1 attacks (rules were written from this phase)", b.p1, "detection rate, in-sample"),
    row("LLMail benign emails (`emails_for_fp_tests`)", b.benign, "false-positive rate"),
    row("Hand-written ordinary emails (authored for this repo)", b.hard, "false-positive rate"), "",
    "## Findings per rule on the phase 2 held-out set", "", "| Rule | Emails flagged |", "|---|---|", ...top, "",
    "## How to read this (limits)", "",
    "- **Static regex cannot keep up with adaptive attacks.** LLMail-Inject attacks were adaptive: participants rewrote prompts until they got past ML defenses. Paraphrased, translated, or politely worded requests (\"could you confirm with my colleague at …\") get past these rules. On held-out data about a third of attacks raise no finding at all, and more than half raise nothing above low severity. That is the honest picture.",
    "- **Held-out is approximate.** Rules were written by reading phase 1 attacks and scoring an earlier sample of 1,000 phase 2 attacks (about 20 of which were read). Those 1,000 are excluded here; the 500 held-out items were not looked at. Phase 2 had stronger defenses and a blocklist, so its attacks differ from phase 1.",
    "- **The benign sets are small and easy.** The 203 LLMail benign emails rarely contain addresses or requests. The 30 hand-written emails are deliberately harder (RSVPs, \"send the contract to legal@…\") and show that `llmail_send_to_address` fires on normal mail, which is why it is low severity. Real inboxes and docs will produce more false positives than these numbers suggest.",
    "- **Detection is not prevention.** A finding means \"look at this\"; a clean result does not mean a document is safe. The real fix is to gate send/post tools behind user confirmation.",
    "- The ADSF tab is not part of the overall score, so these rules do not change agent scores.", ""
  ].join("\n");
}
if (require.main === module) {
  const doc = render(bench()), p = path.join(ROOT, "docs", "LLMAIL_BENCHMARK.md");
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(p) || fs.readFileSync(p, "utf8") !== doc) { console.error("docs/LLMAIL_BENCHMARK.md is stale; run npm run bench:llmail"); process.exit(1); }
    console.log("LLMail benchmark doc up to date");
  } else { fs.writeFileSync(p, doc); console.log(doc.split("\n").slice(8, 16).join("\n")); }
}
module.exports = { bench, render };
