#!/usr/bin/env node
// Builds the browser engine (web-dist/agent-ops-check.js) from the SAME src/ and rules/ the CLI uses.
// Usage: node scripts/build-web.js [--labs <path-to-arup-banerjee-labs>]   (copies the bundle + JSZip there)
"use strict";
const fs = require("fs"), path = require("path"), esbuild = require("esbuild");
const ROOT = path.join(__dirname, ".."), OUT = path.join(ROOT, "web-dist");
const V = "/aoc"; // virtual install path inside the in-memory fs

function walk(dir, f) { for (const e of fs.readdirSync(dir).sort()) { const p = path.join(dir, e); fs.statSync(p).isDirectory() ? walk(p, f) : f(p); } }
const assets = {};
const add = (abs) => { assets[V + "/" + path.relative(ROOT, abs).split(path.sep).join("/")] = fs.readFileSync(abs, "utf8"); };
walk(path.join(ROOT, "rules"), add);
walk(path.join(ROOT, "data", "standards"), add);
add(path.join(ROOT, "src", "ste", "core.js")); // src/ste/ui.js inlines it into ste.html
const vendorDir = path.join(ROOT, "src", "labs", "vendor");
const vendor = fs.readdirSync(vendorDir).filter((f) => f.endsWith(".js")).sort();
// labs/index.js reads the vendor source and hands it to vm; the browser vm shim runs the pre-wrapped copy instead.
for (const f of vendor) assets[V + "/src/labs/vendor/" + f] = "/* bundled as a function, see web/shims/vm.js */";

const plugin = {
  name: "aoc",
  setup(b) {
    b.onResolve({ filter: /^(aoc-assets|aoc-vendor)$/ }, (a) => ({ path: a.path, namespace: "aoc" }));
    b.onLoad({ filter: /.*/, namespace: "aoc" }, (a) => a.path === "aoc-assets"
      ? { contents: "module.exports=" + JSON.stringify(assets), loader: "js" }
      : { contents: "module.exports={" + vendor.map((f) => JSON.stringify(f) + ":function(window,document,localStorage,navigator,console,setTimeout,clearTimeout,fetch,XMLHttpRequest,URL,Blob,self){\n" + fs.readFileSync(path.join(vendorDir, f), "utf8") + "\n}").join(",\n") + "}", loader: "js" });
    // __dirname -> virtual path, so path.join(__dirname, "..", "rules") resolves inside the in-memory fs.
    b.onLoad({ filter: /[\\/]src[\\/].*\.js$/ }, (a) => ({ contents: fs.readFileSync(a.path, "utf8").replace(/\b__dirname\b/g, JSON.stringify(V + "/" + path.relative(ROOT, path.dirname(a.path)).split(path.sep).join("/"))), loader: "js" }));
  }
};
const shim = (n) => path.join(ROOT, "web", "shims", n);
async function build() {
  fs.mkdirSync(OUT, { recursive: true });
  const rv = JSON.parse(fs.readFileSync(path.join(ROOT, "rules", "VERSION.json"), "utf8"));
  const banner = "/*! agent-ops-check browser engine v" + require("../package.json").version + " · rules " + rv.version + " (" + rv.date + ") · MIT · generated by scripts/build-web.js from the CLI's src/ and rules/ — do not edit. No network code. */";
  await esbuild.build({
    entryPoints: [path.join(ROOT, "web", "entry.js")], bundle: true, format: "iife", globalName: "AgentOpsCheck", platform: "browser", target: ["es2020"],
    outfile: path.join(OUT, "agent-ops-check.js"), banner: { js: banner }, legalComments: "none", logLevel: "warning",
    alias: { fs: shim("fs.js"), path: require.resolve("path-browserify"), vm: shim("vm.js"), zlib: shim("empty.js"), os: shim("empty.js"), http: shim("empty.js"), https: shim("empty.js"), child_process: shim("empty.js") },
    inject: [shim("process.js")], plugins: [plugin]
  });
  fs.copyFileSync(require.resolve("jszip/dist/jszip.min.js"), path.join(OUT, "jszip.min.js"));
  // Sample agents for the "try a sample" buttons (same files the parity test and golden results use).
  const samples = {};
  for (const n of ["bad-agent", "good-agent"]) { const e = []; walk(path.join(ROOT, "examples", n), (p) => e.push({ path: path.relative(path.join(ROOT, "examples", n), p).split(path.sep).join("/"), text: fs.readFileSync(p, "utf8") })); samples[n] = e; }
  for (const f of ["original.txt", "rewrite.txt", "approved-words.txt"]) samples["ste/" + f] = fs.readFileSync(path.join(ROOT, "examples", "ste", f), "utf8");
  fs.writeFileSync(path.join(OUT, "samples.js"), "/*! agent-ops-check sample inputs (examples/), generated by scripts/build-web.js */\nwindow.AOC_SAMPLES=" + JSON.stringify(samples).replace(/</g, "\\u003c") + ";\n");
  fs.writeFileSync(path.join(OUT, "BUILD.json"), JSON.stringify({ version: require("../package.json").version, rules: rv }, null, 2) + "\n");
  const li = process.argv.indexOf("--labs");
  if (li > 0) {
    const dest = path.join(path.resolve(process.argv[li + 1]), "agent-ops-check", "vendor");
    fs.mkdirSync(dest, { recursive: true });
    for (const f of ["agent-ops-check.js", "jszip.min.js", "samples.js", "BUILD.json"]) fs.copyFileSync(path.join(OUT, f), path.join(dest, f));
    console.log("copied to " + dest);
  }
  console.log("built " + path.relative(ROOT, OUT) + "/agent-ops-check.js");
}
build().catch((e) => { console.error(e); process.exit(1); });
