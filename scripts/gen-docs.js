#!/usr/bin/env node
// Generates the "Needs and checks" section of README.md from docs/checks-catalog.yaml and rules/*.yaml.
// Usage: node scripts/gen-docs.js [--check]
"use strict";
const fs = require("fs"), path = require("path"), yaml = require("js-yaml");
const { groupStandards } = require("../src/standards-groups");
const ROOT = path.join(__dirname, "..");
const START = "<!-- CHECKS:START (generated by npm run docs; do not edit) -->", END = "<!-- CHECKS:END -->";
const load = (p) => yaml.load(fs.readFileSync(path.join(ROOT, p), "utf8"));
const cell = (s) => String(s == null ? "" : s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (s) => "`" + String(s).replace(/`/g, "'").replace(/\|/g, "\\|") + "`";
const short = (s, n = 90) => (s.length > n ? s.slice(0, n) + "…" : s);

function yamlRules() {
  const R = {};
  const add = (scanner, list) => (list || []).forEach((r) => (R[scanner + "." + r.id] = r));
  const c = load("rules/crossover.yaml"), a = load("rules/actions.yaml"), i = load("rules/injection.yaml"), ec = load("rules/execconfig.yaml");
  add("crossover", c.hardcoded); add("actions", a.risky_reads);
  add("injection", i.instructions); add("injection", i.exfil_links); add("injection", i.hidden_text); add("injection", i.llmail); add("execconfig", ec.rules);
  return { R, secrets: c.secrets || [], pii: c.pii || [] };
}
function healthChecks() {
  const src = fs.readFileSync(path.join(ROOT, "src/labs/vendor/agent-health-checker.js"), "utf8");
  const out = [], seen = new Set(), re = /id:\s*"(\w+)",\s*title:\s*"([^"]+)"/g; let m;
  while ((m = re.exec(src))) if (!seen.has(m[1])) { seen.add(m[1]); out.push({ id: m[1], title: m[2] }); }
  return out;
}
function healthPlus() {
  const src = fs.readFileSync(path.join(ROOT, "src/labs/health-plus.js"), "utf8");
  const out = [], re = /id:\s*"(\w+)"[\s\S]*?msg:\s*"([^"]+)"/g; let m;
  while ((m = re.exec(src))) out.push({ id: m[1], msg: m[2] });
  return out;
}
function documentedIds() {
  const cat = load("docs/checks-catalog.yaml"), { R } = yamlRules();
  return { catalog: Object.keys(cat.checks), yaml: Object.keys(R), health: healthChecks().map((h) => "health." + h.id), healthPlus: healthPlus().map((h) => "health+." + h.id) };
}

// Benchmark figures are read from the generated docs/LLMAIL_BENCHMARK.md (kept fresh by npm run bench:llmail:check).
function llmailStats() {
  const md = fs.readFileSync(path.join(ROOT, "docs/LLMAIL_BENCHMARK.md"), "utf8");
  const row = (label) => {
    const line = md.split("\n").find((l) => l.startsWith("| " + label));
    if (!line) throw new Error("LLMAIL_BENCHMARK.md row missing: " + label);
    return line.split("|").slice(1, -1).map((x) => x.trim());
  };
  const h = row("Phase 2 held-out attacks"), b = row("LLMail benign emails");
  const n = (s) => (s.match(/\((\d+)\/(\d+)\)/) || []).slice(1);
  return { rules: (load("rules/injection.yaml").llmail || []).length, heldout: n(h[3])[1], any: h[3].split(" ")[0], medium: h[4].split(" ")[0], before: h[2].split(" ")[0], fp: n(b[3])[0] + "/" + n(b[3])[1] };
}
function standardsLines(need) {
  const groups = (load("docs/checks-catalog.yaml").standards_groups || []).filter((g) => g.need === need);
  const L = [];
  for (const g of groupStandards(groups)) {
    L.push("**" + g.title + " maps to** (✅ checked, 🟡 partly checked; from `data/standards/`, \"maps to\", not compliance):", "");
    for (const fw of g.frameworks) L.push("- [" + fw.name + "](" + fw.source + "): " + fw.items.map((it) => it.icon + " " + it.id + " " + it.title).join("; "));
    L.push("");
  }
  return L;
}

function generate() {
  const cat = load("docs/checks-catalog.yaml"), { R, secrets, pii } = yamlRules();
  const L = [START, ""];
  for (const need of cat.needs) {
    L.push("### " + need.title, "", "**The need.**", "");
    need.need.forEach((n) => L.push("- " + n));
    const ids = Object.keys(cat.checks).filter((k) => cat.checks[k].need === need.id);
    L.push("", "**Where:** " + need.tab + ".", "");
    if (need.id === "evals") {
      L.push("**Checks that address it:** `agent-ops-check evals <folder>` writes an offline eval set (JSONL) from your prompts and tool definitions, and the Standards map shows how findings map to 10 frameworks in `data/standards/` (✅ evidence found, 🟡 partial, ⬜ not found). It says \"maps to\", never \"compliant\".", "");
      continue;
    }
    L.push("**Checks that address it:** " + ids.map((k) => "`" + k + "`").join(", "), "");
    L.push("| Rule ID | Severity | What it looks for | Example finding | How to fix |", "|---|---|---|---|---|");
    for (const id of ids) {
      const c = cat.checks[id], y = R[id];
      let looks = c.looks_for, sev = c.severity || (y && y.severity) || "";
      if (y) {
        looks = (y.message ? y.message + " " : "") + "Pattern: " + code(short(y.pattern));
        if (!sev) sev = "medium";
      }
      if (c.family === "secrets") looks = "Hardcoded secrets (values are masked): " + secrets.map((s) => "`" + s.id + "`").join(", ") + ". Patterns in `rules/crossover.yaml`.";
      if (c.family === "pii") looks = "Personal data: " + pii.map((s) => "`" + s.id + "`").join(", ") + " (card numbers are Luhn-checked). Patterns in `rules/crossover.yaml`.";
      if (c.family === "health") looks += " IDs: " + healthChecks().map((h) => "`" + h.id + "` (" + h.title + ")").join(", ") + ".";
      if (c.family === "healthplus") looks += " IDs: " + healthPlus().map((h) => "`" + h.id + "` (" + h.msg + ")").join(", ");
      if (!looks) throw new Error("No description for " + id);
      L.push("| " + ["`" + id + "`", sev, looks, c.example, c.fix].map(cell).join(" | ") + " |");
    }
    L.push("");
    if (need.id === "injection") {
      const s = llmailStats();
      L.push("**Microsoft LLMail-Inject dataset.** " + s.rules + " `injection.llmail_*` rules are derived from Microsoft's [LLMail-Inject](https://huggingface.co/datasets/microsoft/llmail-inject-challenge) dataset (MIT License; see `THIRD_PARTY_NOTICES.md`). On " + s.heldout + " held-out attacks the scan flags " + s.any + " at any severity and " + s.medium + " at medium or higher (" + s.before + " before these rules), with " + s.fp + " false positives on the dataset's benign emails. About a third of attacks are still missed. Details: [docs/LLMAIL_BENCHMARK.md](docs/LLMAIL_BENCHMARK.md).", "");
    }
    if (need.id === "execconfig") {
      const ec = load("rules/execconfig.yaml");
      L.push("**Lock mode (CLI, offline).** `agent-ops-check <folder> --lock` writes `.agent-ops-lock.json` with the SHA-256 of every execution-config file in the folder (`lock_files` in `rules/execconfig.yaml`). Every later scan of that folder compares against it automatically and reports `lock_changed`, `lock_added` and `lock_removed`; `--verify-lock` makes the lockfile required (exit 2 if missing) and `--no-lock` skips it. Approve reviewed changes by running `--lock` again and committing the file. Names ending in a dot or space are matched as the real name and reported as `lookalike_name`. The browser version runs the static rules only.", "");
      L.push("**Sources (rule `source` metadata in `rules/execconfig.yaml`; their findings, not ours):**", "");
      Object.keys(ec.sources).forEach((k) => L.push("- `" + k + "`: " + String(ec.sources[k]).trim()));
      L.push("", "**What it can't see.** " + require("../src/scanners/execconfig").LIMITS, "");
    }
    L.push(...standardsLines(need.id));
  }
  L.push("_Standards and datasets are named for reference only. This project is not affiliated with or endorsed by Microsoft, OWASP, NIST, ISO, MITRE, CSA, Anthropic or the EU._", "");
  L.push("_Rules version " + load("rules/VERSION.json").version + ". File types: code, config (JSON/YAML/TOML/.env names), prompts (.md/.txt), Jupyter notebooks (.ipynb code and markdown cells, outputs ignored; findings show cell N, line M), transcripts (.jsonl), bill exports (CSV/JSON), and zips of these._", "", END);
  return L.join("\n");
}

function render(readme) {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < 0) throw new Error("README markers missing");
  return readme.slice(0, a) + generate() + readme.slice(b + END.length);
}

// Data for the "What it checks" section of the Labs page (written by scripts/build-web.js).
function webCheckStandards() {
  return { groups: groupStandards(load("docs/checks-catalog.yaml").standards_groups || []), llmail: llmailStats() };
}
module.exports = { generate, render, documentedIds, webCheckStandards, START, END };
if (require.main === module) {
  const p = path.join(ROOT, "README.md"), cur = fs.readFileSync(p, "utf8"), next = render(cur);
  if (process.argv.includes("--check")) { if (cur !== next) { console.error("README is out of date: run npm run docs"); process.exit(1); } console.log("README up to date"); }
  else { fs.writeFileSync(p, next); console.log("README updated"); }
}
